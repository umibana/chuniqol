#pragma once
#include <cstring>

// This exact SDHD 2.50 image was checked against each mod's native instruction
// signatures. Keep the upstream profile and all per-hook byte checks intact.
namespace local_profile {
inline bool matches(const unsigned char* digest) {
    const unsigned char expected[32] = {
        0xbf,0x5f,0x17,0x75,0x4a,0x19,0x12,0x10,
        0xde,0xb5,0x2e,0x68,0x5e,0xe9,0xc2,0x24,
        0x6e,0xe9,0x07,0x01,0x0a,0x9f,0xec,0x43,
        0x6c,0xa4,0xb6,0xb7,0x6e,0xef,0x98,0x00
    };
    return std::memcmp(digest, expected, sizeof(expected)) == 0;
}
}
